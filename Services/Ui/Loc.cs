    public static string Locale => _locale;

    public static event Action? Changed;

    public static void SetLocale(string? locale)
    {
        var next = string.Equals(locale, "ru", StringComparison.OrdinalIgnoreCase) ? "ru" : "en";
        bool changed = _locale != next;
        _locale = next;
        if (changed)
            Changed?.Invoke();
    }

    /// <summary>
    /// "{n} unit" with the right plural form. The unit key holds "one|few|many" (RU: игра|игры|игр;
    /// EN: game|games|games). Falls back to the key when it is missing or malformed.
    /// </summary>
    public static string Plural(string unitKey, int count)
    {
        var forms = T(unitKey).Split('|');
        if (forms.Length != 3) return count + " " + unitKey;
        return count + " " + forms[PluralIndex(count, _locale)];
    }

    /// <summary>0 = one, 1 = few (RU 2–4), 2 = many. EN only distinguishes one / many.</summary>
    public static int PluralIndex(int count, string? locale)
    {
        int n = Math.Abs(count);
        if (!string.Equals(locale, "ru", StringComparison.OrdinalIgnoreCase))
            return n == 1 ? 0 : 2;
        int mod10 = n % 10, mod100 = n % 100;
        if (mod10 == 1 && mod100 != 11) return 0;
        if (mod10 is >= 2 and <= 4 && mod100 is < 12 or > 14) return 1;
        return 2;
    }

    /// <summary>Format Loc.T key that contains {0} placeholders.</summary>
    public static string Tf(string key, params object[] args)
    {
        try { return string.Format(T(key), args); }
        catch { return T(key); }
    }

    public static string T(string key)
    {
        if (!Map.TryGetValue(key, out var pair)) return key;
        return _locale == "ru" ? pair.Ru : pair.En;
    }
